export async function seedPublicHolidays(prisma: PrismaClient) {
  console.log('🎉 Starting public holidays seed...');

  for (const countryData of holidaysData) {
    const country = await prisma.country.findUnique({
      where: { name: countryData.countryName },
    });

    if (!country) {
      console.log(`⚠️  Country not found: ${countryData.countryName}`);
      continue;
    }

    console.log(`📅 Adding holidays for ${countryData.countryName}...`);

    for (const holiday of countryData.holidays) {
      await prisma.publicHoliday.upsert({
        where: {
          countryId_name_date: {
            countryId: country.id,
            name: holiday.name,
            date: holiday.date,
          },
        },
        update: {
          localName: holiday.localName,
          type: holiday.type,
          description: holiday.description,
        },
        create: {
          countryId: country.id,
          name: holiday.name,
          localName: holiday.localName,
          date: holiday.date,
          type: holiday.type || 'public',
          isRecurring: true,
          description: holiday.description,
        },
      });
    }

    console.log(`✅ Added ${countryData.holidays.length} holidays for ${countryData.countryName}`);
  }

  console.log('🎉 Public holidays seed completed!');
}
